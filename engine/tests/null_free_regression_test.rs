//! 0118-MERIDIAN V10: files with no blank cell produce the numbers they produced before.
//!
//! The 0118 change reads employee identity from the row ordinals the builder reports instead of
//! recomputing it from the raw group column. On a file with no blank model cell and no third
//! group value those two are the same list, so every number the engine returns must match the
//! pre-0118 engine. This test pins that.
//!
//! HOW THE GOLDEN WAS MADE. `fixtures/0118-null-free-golden.txt` holds one line per case,
//! `name<TAB>canonical-json`: the engine's result (serde_json) with the four fields 0118 added
//! removed (`analysed_reference_count`, `analysed_target_count`, `excluded_rows`,
//! `adjustments_on_excluded_rows`). It was recorded by running THIS FILE against the pre-0118
//! engine source (commit 8e4e552, `main` before the 0118 epic), where those four fields do not
//! exist and the removal is a no-op. It is not regenerated from the current engine: a changed
//! number here is a changed number on a null-free file.
//!
//! TOLERANCE. Strings, bools, nulls, integers, object keys and array lengths must match exactly.
//! Every float must satisfy |a-b| <= 1e-9 * max(1, |a|, |b|). Bit-identity across machines is not
//! available: the linear algebra underneath (nalgebra over matrixmultiply) picks AVX/FMA or
//! scalar kernels at run time from the CPU it finds, and those round the last bit differently,
//! so the same engine gives different low bits on different x86-64 hosts. 1e-9 sits about six
//! orders of magnitude above that noise and far below any real change. The worst relative
//! difference per case is printed with --nocapture and named in the failure message.
//!
//! 0120-MERIDIAN S1/S4: THE GOLDEN IS NOT REGENERATED. Two kinds of field may differ now, and the
//! test names them (`ENGINE_LAYER_METADATA`, `NORMALISED_CASES`, `NORMALISED_DRIVER_FIELDS`):
//!
//!   * the three provenance keys the engine layer adds to `run_metadata`
//!     (`reference_coefficients_used`, `engine_version`, `method`);
//!   * on a case with a categorical predictor, the per-level driver vectors
//!     (`detailed_explained`, `detailed_unexplained`) and `run_metadata.normalization`, because
//!     those are the point of the change. They are not skipped: their estimates must still SUM
//!     to the golden's aggregate `explained_gap` / `unexplained_gap` (adding-up), must contain
//!     every name the golden has, and the only extra name is the base level.
//!
//! Every other field of every case, aggregates, standard errors, percentages, the whole remedy,
//! verify, defensibility and frontier outputs, still equals the pre-0118 golden at 1e-9. The
//! request helper (`support/engine_requests.rs`) changed only to name `"Pooled"` explicitly
//! (an absent scheme is now an error); the numbers of those cases are the ones the engine's old
//! silent fallback produced. New normalised expectations live in
//! `oaxaca_blinder/tests/fixtures/norm_goldens_r.json`, generated by R.
//!
//! 0120-MERIDIAN S6/S7/S8 (still NOT regenerated). Three more kinds of field may differ, each
//! named below and each held to an independent check instead of being skipped:
//!
//!   * the fields S6-S8 ADD (`support`, `warnings`, `quantile_report`, `interval`, each
//!     adjustment's `extrapolated`, each frontier point's `group_coefficient`,
//!     `degrees_of_freedom` and `confidence_level`): must be PRESENT with the right shape, then dropped. Their values are
//!     pinned against R in `support_diagnostics_test`, `intervals_test` and `quantile_report_test`.
//!   * the interval-derived fields, because the interval is Student t now, not z (S7): lower and
//!     upper bound, `is_defensible` and its message, frontier `p_value` / `is_significant`. They
//!     are RECOMPUTED from the golden's own numbers (`half-width_z * t/z` on the engine's
//!     degrees of freedom; `2 * pt(-|t|, df)` from the golden's t) and must equal the engine's.
//!   * the two range-target optimise cases, whose payments are the interval: their pay fields are
//!     checked against their own invariants (paid exactly to the bound, totals add up) and every
//!     other field still equals the golden.
//!
//! 0120-MERIDIAN T8 (still NOT regenerated). One case moved BY DESIGN: `optimize/noisy/pooled_target`.
//! The golden pins the pre-T8 Pooled target, which stacked both groups with no group indicator
//! (Neumark). The target now fits the pooled regression WITH the indicator and reads fair wages
//! at indicator 0, with the interval from that same fit, so every fair wage, payment, total and
//! gap of that case moved, and its interval has `n - k - 1` residual df. The old text cannot be
//! the expectation for those fields. They are held to an independent oracle instead
//! (`POOLED_TARGET_CASES`, `check_pooled_target_case`): the pooled `lm` of the fixture's own
//! cells, fitted in plain `std` by `support::ols`, which shares no code with the engine (and
//! `pooled_target_test` holds the same line to R's `lm` / `predict.lm`). Every field outside
//! that list, and every Reference-target case, is still compared with the golden at 1e-9.
//!
//! 0122-MERIDIAN V16 (still NOT regenerated, with ONE exception). The remedy changed what it
//! reports, so the comparator names every difference and holds each to an independent check:
//!
//!   * the keys 0122 ADDED to every optimise and defensibility result (`ADDED_BY_0122`, and per
//!     adjustment `source`, `range_position`, `range_position_before`): must be PRESENT and
//!     well-formed, then dropped. Their values are pinned against R in `remedy_oracle_test`.
//!   * `defensibility/*` report the gap with `optimize`'s sign now (compared minus reference,
//!     negative while underpaid; T7): `original_gap`, `new_gap` and `original_unexplained_gap` are
//!     compared against the NEGATED golden. `new_unexplained_gap` is the line REFITTED on the
//!     schedule, which moves with the reference raise every one of these schedules contains
//!     (row 52), so it is not the negated fixed-line figure; it is pinned against an R refit in
//!     `remedy_oracle_test` and checked here to differ from the negated golden by exactly the
//!     fixed-line figure's own refit shift sign (finite, and on the golden's side of zero).
//!   * `optimize/noisy/lower_bound` and `upper_bound`: `original_unexplained_gap` is the MIDPOINT
//!     line's now (T6), so it equals the default case's, not the mean shortfall to the bound.
//!   * `optimize/noisy/pooled_target`: `new_unexplained_gap` is now held to a refit (see
//!     `check_pooled_target_case`), where before it was unguarded.
//!   * `optimize/noisy/forensic_both` is the ONE regenerated case (REM-3): the reference raises
//!     were credited to the compared group. Its `new_gap`, `new_unexplained_gap` and
//!     `required_budget` in the golden are now the values `verification/gen_remedy_goldens.R`
