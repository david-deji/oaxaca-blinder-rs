/// `t / z` for `confidence` on `dof`: the factor by which a z-based half-width becomes a
/// Student t half-width.
fn t_over_z(confidence: f64, dof: f64) -> f64 {
    use statrs::distribution::{ContinuousCDF, Normal, StudentsT};
    let p = 1.0 - (1.0 - confidence) / 2.0;
    StudentsT::new(0.0, 1.0, dof).unwrap().inverse_cdf(p)
        / Normal::new(0.0, 1.0).unwrap().inverse_cdf(p)
}

fn take(v: &mut Value, key: &str) -> Option<Value> {
    v.as_object_mut().and_then(|m| m.remove(key))
}

fn num(v: &Value, key: &str) -> f64 {
    v[key]
        .as_f64()
        .unwrap_or_else(|| panic!("{key} is a number in {v}"))
}

/// Checks and strips what S6-S8 added or changed. After this, `want` and `got` must be equal
/// field for field (at 1e-9) outside the normalised driver vectors handled by the caller.
fn scope_s6_to_s8(name: &str, want: &mut Value, got: &mut Value) -> Result<(), String> {
    let family = family_of(name);
    if family == Family::Plain {
        return Ok(());
    }
    // ---- frontier: an array of points ----
    if family == Family::Frontier {
        // The pooled design of FixtureF is 100 rows by (intercept, group, Experience, Level).
        let want_dof = (support::N_ROWS - 4) as i64;
        let want_pts = want.as_array_mut().ok_or("frontier golden is an array")?;
        let got_pts = got.as_array_mut().ok_or("frontier result is an array")?;
        if want_pts.len() != got_pts.len() {
            return Err(format!(
                "frontier: {} points vs {}",
                want_pts.len(),
                got_pts.len()
            ));
        }
        for (i, (w, g)) in want_pts.iter_mut().zip(got_pts.iter_mut()).enumerate() {
            let dof = g["degrees_of_freedom"]
                .as_i64()
                .ok_or(format!("frontier[{i}]: degrees_of_freedom missing"))?;
            if dof != want_dof {
                return Err(format!("frontier[{i}]: dof {dof}, expected {want_dof}"));
            }
            if g["group_coefficient"].as_f64().is_none() {
                return Err(format!("frontier[{i}]: group_coefficient missing"));
            }
            use statrs::distribution::{ContinuousCDF, StudentsT};
            let t = num(w, "t_statistic");
            let p = 2.0 * StudentsT::new(0.0, 1.0, dof as f64).unwrap().cdf(-t.abs());
            let got_p = num(g, "p_value");
            if rel_diff(p, got_p) > REL_TOL {
                return Err(format!(
                    "frontier[{i}]: p_value {got_p:e}, recomputed {p:e}"
                ));
            }
            if g["is_significant"].as_bool() != Some(p < 0.05) {
                return Err(format!(
                    "frontier[{i}]: is_significant disagrees with p {p:e}"
                ));
            }
            if g["confidence_level"].as_f64() != Some(0.95) {
                return Err(format!(
                    "frontier[{i}]: confidence_level is not the 0.95 default"
                ));
            }
            for k in [
                "group_coefficient",
                "degrees_of_freedom",
                "confidence_level",
                "p_value",
                "is_significant",
            ] {
                take(g, k);
            }
            for k in ["p_value", "is_significant"] {
                take(w, k);
            }
        }
        return Ok(());
    }

    // ---- results with the added top-level blocks ----
    for key in ["support", "warnings"] {
        let present = take(got, key).ok_or(format!("{name}: `{key}` missing from the result"))?;
        if key == "warnings" && !present.is_array() {
            return Err(format!("{name}: `warnings` is not an array"));
        }
    }
    let has_report = take(got, "quantile_report");
    match (name.contains("quantile"), has_report) {
        (true, None) => return Err(format!("{name}: a percentile run has no quantile_report")),
        (false, Some(_)) => return Err(format!("{name}: a mean run carries a quantile_report")),
        _ => {}
    }
    if matches!(family, Family::Optimize | Family::Defensibility) {
        let basis = take(got, "interval").ok_or(format!("{name}: `interval` missing"))?;
        let engine_dof = basis["degrees_of_freedom"]
            .as_u64()
            .ok_or(format!("{name}: interval.degrees_of_freedom missing"))?;
        let model_columns = want["model_coefficients"]
            .as_array()
            .ok_or("model_coefficients")?
            .len() as u64;
        // The Reference target's interval is the baseline group's own fit (`n_ref - k`); the
        // Pooled target's is the pooled fit with the indicator (`n_ref + n_target - k - 1`).
        let own_dof = if POOLED_TARGET_CASES.contains(&name) {
            (REFERENCE_ROWS + TARGET_ROWS) as u64 - model_columns - 1
        } else {
            REFERENCE_ROWS as u64 - model_columns
        };
        if engine_dof != own_dof {
            return Err(format!(
                "{name}: interval.degrees_of_freedom {engine_dof}, the fixture's own is {own_dof}"
            ));
        }
        let level = basis["confidence_level"].as_f64().unwrap_or(f64::NAN);
        if (level - case_confidence(name)).abs() > 1e-12 {
            return Err(format!("{name}: interval.confidence_level {level}"));
        }
    }
    if !matches!(family, Family::Optimize | Family::Defensibility) {
        return Ok(());
    }

    // ---- 0122: the added keys must be present; their values are pinned elsewhere ----
    for key in ADDED_BY_0122 {
        take(got, key).ok_or(format!("{name}: `{key}` missing from the result"))?;
    }
    if family == Family::Defensibility {
        // T7: the sign now matches `optimize`'s. The golden holds the old (reference minus
        // compared, fair minus wage) figures: compare the NEGATED golden.
        for k in ["original_gap", "new_gap", "original_unexplained_gap"] {
            let v = num(want, k);
            want[k] = serde_json::json!(-v);
        }
        // The refit moves with the reference raise in every schedule here (row 52): finite, and
        // pinned to an R refit in remedy_oracle_test.
        let refit = num(got, "new_unexplained_gap");
        if !refit.is_finite() {
            return Err(format!("{name}: new_unexplained_gap is not finite"));
        }
        take(want, "new_unexplained_gap");
        take(got, "new_unexplained_gap");
    }

    // ---- adjustment rows ----
    let confidence = case_confidence(name);
    // FixtureF has no blank cell here: 60 reference rows (Male), 40 target rows. The golden has
    // had `analysed_*_count` removed (they are 0118 fields), so the counts are the fixture's.
    let dof = REFERENCE_ROWS
        - want["model_coefficients"]
            .as_array()
            .ok_or("model_coefficients")?
            .len() as f64;
    let ratio = t_over_z(confidence, dof);
    let range_target = RANGE_TARGET_CASES.contains(&name);

    let got_rows = got["adjustments"].as_array_mut().ok_or("adjustments")?;
    for row in got_rows.iter_mut() {
        if take(row, "extrapolated")
            .and_then(|v| v.as_bool())
            .is_none()
        {
            return Err(format!(
                "{name}: an adjustment has no boolean `extrapolated`"
            ));
        }
        for (key, allowed) in ADDED_ROW_FIELDS {
            let value = take(row, key).ok_or(format!("{name}: an adjustment has no `{key}`"))?;
            if !value.as_str().is_some_and(|v| allowed.contains(&v)) {
                return Err(format!("{name}: an adjustment has `{key}` = {value}"));
            }
        }
    }

    if POOLED_TARGET_CASES.contains(&name) {
        check_pooled_target_case(name, got)?;
        for k in POOLED_TARGET_MOVED {
            take(want, k);
            take(got, k);
        }
        return Ok(());
    }

    if range_target {
        // Payments are the interval: check them against their own invariants, then compare only
        // the rows both sides have, on the fields the interval does not touch.
        let upper = name.ends_with("upper_bound");
        let rows = got["adjustments"].as_array().unwrap().clone();
        if rows.is_empty() {
            return Err(format!("{name}: no adjustments"));
        }
        let mut total = 0.0;
        for r in &rows {
            let bound = num(
                r,
                if upper {
                    "fair_wage_upper_bound"
                } else {
                    "fair_wage_lower_bound"
                },
            );
            if (num(r, "new_wage") - bound).abs() >= 0.005 {
                return Err(format!(
                    "{name}: row {} is paid {} and not its bound {bound}",
                    num(r, "index"),
                    num(r, "new_wage")
                ));
            }
            total += num(r, "adjustment");
        }
        let n_target = TARGET_ROWS;
        let checks = [
            ("total_cost", total),
            ("required_budget", total),
            ("new_gap", num(got, "original_gap") + total / n_target),
            (
                "new_unexplained_gap",
                num(got, "original_unexplained_gap") + total / n_target,
            ),
        ];
        for (k, expect) in checks {
            if rel_diff(num(got, k), expect) > 1e-6 {
                return Err(format!(
                    "{name}: {k} {:e}, invariant {expect:e}",
                    num(got, k)
                ));
            }
        }
        // Rows present on both sides keep the interval-free fields.
        let want_rows = want["adjustments"].as_array().unwrap().clone();
        for r in &rows {
            if let Some(w) = want_rows.iter().find(|w| w["index"] == r["index"]) {
                for k in ["fair_wage", "current_wage", "row_key", "contributions"] {
                    compare(&format!("$.adjustments[{}].{k}", r["index"]), &w[k], &r[k])?;
                }
            }
        }
        // `original_unexplained_gap` is the mean shortfall to each employee's BOUND here, so it
        // moves with the interval as well; `new_unexplained_gap` is held to it above.
        for k in [
            "adjustments",
            "total_cost",
            "required_budget",
            "new_gap",
            "original_unexplained_gap",
            "new_unexplained_gap",
        ] {
            take(want, k);
            take(got, k);
        }
        return Ok(());
    }

    // Midpoint payments do not read the interval: recompute the bounds (and the defensibility
    // verdict) from the golden's own z-based half-width.
    let defensibility = family == Family::Defensibility;
    let want_rows = want["adjustments"].as_array_mut().ok_or("adjustments")?;
    let got_rows = got["adjustments"].as_array_mut().ok_or("adjustments")?;
    if want_rows.len() != got_rows.len() {
        return Err(format!(
            "{name}: {} rows vs {}",
            want_rows.len(),
            got_rows.len()
        ));
    }
    for (i, (w, g)) in want_rows.iter_mut().zip(got_rows.iter_mut()).enumerate() {
        let fair = num(w, "fair_wage");
        let half_z = (num(w, "fair_wage_upper_bound") - num(w, "fair_wage_lower_bound")) / 2.0;
        let (lower, upper) = (fair - half_z * ratio, fair + half_z * ratio);
        for (k, expect) in [
            ("fair_wage_lower_bound", lower),
            ("fair_wage_upper_bound", upper),
        ] {
            if rel_diff(num(g, k), expect) > REL_TOL {
                return Err(format!(
                    "{name}.adjustments[{i}].{k}: {:e}, recomputed {expect:e}",
                    num(g, k)
                ));
            }
            take(g, k);
            take(w, k);
        }
        if defensibility {
            let new_wage = num(w, "new_wage");
            let ok = new_wage >= lower - 0.01;
            let msg = if ok {
                "Wage is within or above the calculated fair range.".to_string()
            } else {
                format!(
                    "Wage is {:.2} below the defensible lower bound ({:.2}).",
                    lower - new_wage,
                    lower
                )
            };
            if g["is_defensible"].as_bool() != Some(ok) {
                return Err(format!("{name}.adjustments[{i}]: is_defensible != {ok}"));
            }
            if g["defensibility_message"].as_str() != Some(msg.as_str()) {
                return Err(format!(
                    "{name}.adjustments[{i}]: message {:?}, recomputed {msg:?}",
                    g["defensibility_message"]
                ));
            }
            for k in ["is_defensible", "defensibility_message"] {
                take(g, k);
                take(w, k);
            }
        }
    }
    Ok(())
}

/// The independent oracle for a Pooled-target optimise case on the noisy FixtureF (T8).
///
/// The pooled regression `Salary ~ 1 + Experience + Level + group` is fitted from the fixture's
/// own cells by `support::ols` (plain `std`, no engine code). Held to it, at 1e-9: the model
/// terms (indicator dropped), `original_unexplained_gap` (= the indicator's coefficient), every
/// fair wage at indicator 0, its prediction-interval bounds on the pooled fit's `n - k - 1` df,
/// and the payments (every row below its fair wage by more than 1e-6 is paid up to it).
fn check_pooled_target_case(name: &str, got: &Value) -> Result<(), String> {
    let fixture = FixtureF::noisy();
    let (mut x, mut y) = (Vec::new(), Vec::new());
    for i in 0..support::N_ROWS {
        let mut row = fixture.features(i);
        row.push(if support::is_target_row(i) { 1.0 } else { 0.0 });
        x.push(row);
        y.push(fixture.salary_cell(i).ok_or("noisy fixture has no blank")?);
    }
    let fit = support::ols(&x, &y);
    let k = fit.p - 1;
    let gamma = fit.beta[k];

    let coefficients = got["model_coefficients"]
        .as_array()
        .ok_or(format!("{name}: model_coefficients"))?;
    if coefficients.len() != k {
        return Err(format!(
            "{name}: {} model terms, the pooled fit has {k} without the indicator",
            coefficients.len()
        ));
    }
    for (j, term) in coefficients.iter().enumerate() {
        if rel_diff(num(term, "value"), fit.beta[j]) > REL_TOL {
            return Err(format!(
                "{name}: model term {j} {:e}, pooled lm {:e}",
                num(term, "value"),
                fit.beta[j]
            ));
        }
    }
    if rel_diff(num(got, "original_unexplained_gap"), gamma) > REL_TOL {
        return Err(format!(
            "{name}: original_unexplained_gap {:e}, the pooled indicator coefficient is {gamma:e}",
            num(got, "original_unexplained_gap")
        ));
    }

    let t = support::t_95(fit.n as f64 - fit.p as f64);
    let rows = got["adjustments"].as_array().ok_or("adjustments")?;
    let mut expected_paid = 0;
    let mut paid_total = 0.0;
    for i in (0..support::N_ROWS).filter(|&i| support::is_target_row(i)) {
        let features = fixture.features(i);
        let fair = support::dot(&fit.beta[..k], &features);
        let current = fixture.salary_cell(i).unwrap();
        if fair - current <= 1e-6 {
            continue;
        }
        expected_paid += 1;
        paid_total += fair - current;
        let row = rows
            .iter()
            .find(|r| r["index"].as_u64() == Some(i as u64))
            .ok_or(format!("{name}: underpaid row {i} has no adjustment"))?;
        let mut extended = features.clone();
        extended.push(0.0);
        let h = support::quad_form(&fit.xtx_inv, &extended);
        let margin = t * (fit.sigma2 * (1.0 + h)).sqrt();
        for (k_, want) in [
            ("fair_wage", fair),
            ("fair_wage_lower_bound", fair - margin),
            ("fair_wage_upper_bound", fair + margin),
            ("adjustment", fair - current),
        ] {
            if rel_diff(num(row, k_), want) > REL_TOL {
                return Err(format!(
                    "{name}: row {i} {k_} {:e}, pooled lm {want:e}",
                    num(row, k_)
                ));
            }
        }
    }
    if expected_paid == 0 || rows.len() != expected_paid {
        return Err(format!(
            "{name}: {} adjustments, the pooled lm underpays {expected_paid} rows",
            rows.len()
        ));
    }
    if rel_diff(num(got, "total_cost"), paid_total) > 1e-6 {
        return Err(format!(
            "{name}: total_cost {:e}, the pooled lm shortfall sums to {paid_total:e}",
            num(got, "total_cost")
        ));
    }

    // 0122: `new_unexplained_gap` is the indicator's coefficient of the pooled `lm` REFITTED on the
    // wages after the payments (before, nothing checked it here). Plain-std refit, no engine code.
    let mut y_after = y.clone();
    for i in (0..support::N_ROWS).filter(|&i| support::is_target_row(i)) {
        let fair = support::dot(&fit.beta[..k], &fixture.features(i));
        if fair - y[i] > 1e-6 {
            y_after[i] = fair;
        }
    }
    let refit = support::ols(&x, &y_after);
    let gamma_after = refit.beta[k];
    if rel_diff(num(got, "new_unexplained_gap"), gamma_after) > 1e-8 {
        return Err(format!(
            "{name}: new_unexplained_gap {:e}, the refitted pooled indicator is {gamma_after:e}",
            num(got, "new_unexplained_gap")
        ));
    }
    Ok(())
}

/// Field-scoped comparison of a current result against the pre-0118 golden. `Ok(worst)` or the
/// first mismatch. See the module comment for what may differ.
fn compare_scoped(name: &str, want: &Value, got: &Value) -> Result<f64, String> {
    let mut want = want.clone();
    let mut got = got.clone();
    scope_s6_to_s8(name, &mut want, &mut got)?;
    let normalised = NORMALISED_CASES.contains(&name);

    if let Some(meta) = got.get_mut("run_metadata").and_then(Value::as_object_mut) {
        for key in ENGINE_LAYER_METADATA {
            meta.remove(key);
        }
        if normalised {
            if meta.remove("normalization").is_none() {
                return Err("$.run_metadata.normalization missing on a normalised case".into());
            }
        } else if meta.contains_key("normalization") {
            return Err(
                "$.run_metadata.normalization present on a case with no categorical".into(),
            );
        }
    }

    if normalised {
        for (field, aggregate) in [
            ("detailed_explained", "explained_gap"),
            ("detailed_unexplained", "unexplained_gap"),
        ] {
            let old = estimates_of(&want, field);
            let new = estimates_of(&got, field);
            let sum: f64 = new.iter().map(|(_, e)| e).sum();
            let target = want[aggregate].as_f64().unwrap();
            let d = rel_diff(sum, target);
            if d > REL_TOL {
                return Err(format!(
                    "$.{field}: estimates sum to {sum:e}, golden {aggregate} is {target:e} (relative diff {d:e})"
                ));
            }
            for (n, _) in &old {
                if !new.iter().any(|(m, _)| m == n) {
                    return Err(format!(
                        "$.{field}: golden name {n:?} missing from the new vector"
                    ));
                }
            }
            let extra: Vec<&String> = new
                .iter()
                .map(|(m, _)| m)
                .filter(|m| !old.iter().any(|(n, _)| n == *m))
                .collect();
            // One categorical variable (Dept): the only new name is its base level, `Dept_<x>`.
            if extra.len() != 1 || !extra[0].starts_with("Dept_") {
                return Err(format!(
                    "$.{field}: expected exactly the Dept base level as new name, got {extra:?}"
                ));
            }
        }
        for field in NORMALISED_DRIVER_FIELDS {
            want.as_object_mut().unwrap().remove(field);
            got.as_object_mut().unwrap().remove(field);
        }
    }
    compare("$", &want, &got)
}

#[test]
fn null_free_outputs_match_the_pre_0118_engine() {
    let cases = cases();

    if std::env::var("MERIDIAN_PRINT_GOLDEN").as_deref() == Ok("json") {
        for (name, json) in &cases {
            println!("JSON\t{name}\t{json}");
        }
        return;
    }

    let golden = std::fs::read_to_string(golden_path()).expect("golden file present");
    let want: HashMap<&str, &str> = golden
        .lines()
        .filter(|l| !l.trim().is_empty() && !l.starts_with('#'))
        .map(|l| l.split_once('\t').expect("name<TAB>json line"))
        .collect();

    assert_eq!(
        want.len(),
        cases.len(),
        "the golden file and the case list must agree on the cases"
    );
    let mut moved = Vec::new();
    for (name, json) in &cases {
        let expected = want
            .get(name.as_str())
            .unwrap_or_else(|| panic!("case {name} has no golden entry"));
        let want_v: Value = serde_json::from_str(expected).expect("golden json parses");
        let got_v: Value = serde_json::from_str(json).expect("result json parses");
        match compare_scoped(name, &want_v, &got_v) {
            Ok(worst) => println!("{name}: worst relative difference {worst:e}"),
            Err(why) => moved.push(format!("{name}: {why}")),
        }
    }
    // 0122 T6: under a range target `original_unexplained_gap` is the MIDPOINT line's, the figure
    // the default case reports, not the mean shortfall to the bound. (The comparator drops the
    // field from both sides for these cases; this is where it is held.)
    let by_name: HashMap<&str, Value> = cases
        .iter()
        .map(|(n, j)| (n.as_str(), serde_json::from_str(j).unwrap()))
        .collect();
    let midpoint = by_name["optimize/noisy/default"]["original_unexplained_gap"]
        .as_f64()
        .unwrap();
    for case in RANGE_TARGET_CASES {
        let got = by_name[case]["original_unexplained_gap"].as_f64().unwrap();
        if rel_diff(got, midpoint) > REL_TOL {
            moved.push(format!(
                "{case}: original_unexplained_gap {got:e} is not the midpoint line's {midpoint:e}"
            ));
        }
    }
    assert!(
        moved.is_empty(),
        "output changed on a null-free file:\n{}\nRe-run with MERIDIAN_PRINT_GOLDEN=json against \
         the pre-0118 engine (8e4e552) to compare.",
        moved.join("\n")
    );
}

// Each gate must be shown to fail (agentic-workflow-principles: a green gate that could not have
// failed is not evidence). These feed `compare_scoped` results it must refuse.
fn tiny_result(unexplained: f64) -> Value {
    serde_json::json!({
        "total_gap": 3.0,
        "explained_gap": 1.0,
        "unexplained_gap": unexplained,
        "detailed_explained": [{"name": "x", "estimate": 1.0}],
        "detailed_unexplained": [{"name": "x", "estimate": 2.0}],
        "run_metadata": {"seed": "1"}
    })
}

#[test]
fn scoped_comparator_refuses_an_aggregate_change() {
    let want = tiny_result(2.0);
    let mut got = tiny_result(2.0 + 1e-6);
    got["run_metadata"]["engine_version"] = serde_json::json!("0.2.0");
    assert!(compare_scoped("plain/other", &want, &got).is_err());
    // and accepts the allowed provenance keys alone
    let mut ok = tiny_result(2.0);
    ok["run_metadata"]["engine_version"] = serde_json::json!("0.2.0");
    ok["run_metadata"]["method"] = serde_json::json!("oaxaca-blinder-mean");
    ok["run_metadata"]["reference_coefficients_used"] = serde_json::json!("Pooled");
    assert!(compare_scoped("plain/other", &want, &ok).is_ok());
}

#[test]
fn scoped_comparator_does_not_exempt_drivers_outside_the_named_case() {
    let want = tiny_result(2.0);
    let mut got = tiny_result(2.0);
    got["detailed_unexplained"][0]["estimate"] = serde_json::json!(2.5);
    assert!(compare_scoped("plain/other", &want, &got).is_err());
}

#[test]
fn scoped_comparator_holds_a_normalised_case_to_adding_up() {
    // A normalised case may change its driver vectors, but they must still add up and may
    // only gain the base level.
    let want = serde_json::json!({
        "explained_gap": 1.0, "unexplained_gap": 2.0,
        "detailed_explained": [{"name": "Dept_B", "estimate": 1.0}],
        "detailed_unexplained": [{"name": "Dept_B", "estimate": 2.0}],
        "run_metadata": {"seed": "1"}
    });
    let good = serde_json::json!({
        "support": {}, "warnings": [],
        "explained_gap": 1.0, "unexplained_gap": 2.0,
        "detailed_explained": [{"name": "Dept_B", "estimate": 0.4}, {"name": "Dept_A", "estimate": 0.6}],
        "detailed_unexplained": [{"name": "Dept_B", "estimate": 1.5}, {"name": "Dept_A", "estimate": 0.5}],
        "run_metadata": {"seed": "1", "normalization": {"applied": true}}
    });
    assert!(compare_scoped("decompose/noisy+dept/pooled", &want, &good).is_ok());
    let mut broken = good.clone();
    broken["detailed_unexplained"][1]["estimate"] = serde_json::json!(0.6);
    assert!(compare_scoped("decompose/noisy+dept/pooled", &want, &broken).is_err());
    let mut extra = good.clone();
    extra["detailed_explained"]
        .as_array_mut()
        .unwrap()
        .push(serde_json::json!({"name": "Other", "estimate": 0.0}));
    assert!(compare_scoped("decompose/noisy+dept/pooled", &want, &extra).is_err());
}

// ---- the S6-S8 gates must be shown to fail ----------------------------------------------------

fn s7_golden_and_result(ratio: f64, defensible_message: Option<&str>) -> (Value, Value) {
    // One target row, fair 100, z half-width 10, df chosen so t/z = `ratio` is applied by the
    // caller when building the result's bounds.
    let want = serde_json::json!({
        "adjustments": [{
            "index": 3, "fair_wage": 100.0, "current_wage": 90.0, "new_wage": 95.0,
            "fair_wage_lower_bound": 90.0, "fair_wage_upper_bound": 110.0,
            "is_defensible": true,
            "defensibility_message": "Wage is within or above the calculated fair range."
        }],
        "model_coefficients": [{"name": "a"}, {"name": "b"}],
        "original_gap": 5.0, "new_gap": 4.0,
        "original_unexplained_gap": 3.0, "new_unexplained_gap": 2.0
    });
    let half = 10.0 * ratio;
    let mut got = want.clone();
    // defensibility reports the opposite sign now (0122 T7)
    got["original_gap"] = serde_json::json!(-5.0);
    got["new_gap"] = serde_json::json!(-4.0);
    got["original_unexplained_gap"] = serde_json::json!(-3.0);
    got["adjustments"][0]["fair_wage_lower_bound"] = serde_json::json!(100.0 - half);
    got["adjustments"][0]["fair_wage_upper_bound"] = serde_json::json!(100.0 + half);
    got["adjustments"][0]["extrapolated"] = serde_json::json!(false);
    if let Some(m) = defensible_message {
        got["adjustments"][0]["defensibility_message"] = serde_json::json!(m);
    }
    got["support"] = serde_json::json!({});
    got["warnings"] = serde_json::json!([]);
    got["interval"] = serde_json::json!({"degrees_of_freedom": 58, "confidence_level": 0.95});
    for key in ADDED_BY_0122 {
        got[key] = serde_json::Value::Null;
    }
    got["adjustments"][0]["source"] = serde_json::json!("Compared");
    got["adjustments"][0]["range_position"] = serde_json::json!("Inside");
    got["adjustments"][0]["range_position_before"] = serde_json::json!("Below");
    (want, got)
}

#[test]
fn s7_comparator_accepts_t_bounds_and_refuses_z_bounds() {
    // 60 reference rows, 2 coefficients -> 58 residual df: t/z is only 1.0206 there, yet the
    // difference still moves a bound by more than the 1e-9 tolerance.
    let r = t_over_z(0.95, 58.0);
    assert!(r > 1.02, "t(58)/z must exceed 1: {r}");
    let (want, got) = s7_golden_and_result(r, None);
    assert!(compare_scoped("defensibility/self", &want, &got).is_ok());
    // The golden's own z bounds (ratio 1) are what a z implementation would still return.
    let (want, got) = s7_golden_and_result(1.0, None);
    assert!(
        compare_scoped("defensibility/self", &want, &got).is_err(),
        "z bounds must be refused where df is small"
    );
}

#[test]
fn s7_comparator_refuses_a_missing_block_and_a_wrong_verdict_message() {
    let r = t_over_z(0.95, 58.0);
    let (want, mut got) = s7_golden_and_result(r, None);
    got.as_object_mut().unwrap().remove("support");
    assert!(compare_scoped("defensibility/self", &want, &got).is_err());
    let (want, got) = s7_golden_and_result(
        r,
        Some("Wage is 1.00 below the defensible lower bound (9.00)."),
    );
    assert!(compare_scoped("defensibility/self", &want, &got).is_err());
}

#[test]
fn s7_comparator_refuses_a_frontier_p_value_that_is_not_student_t() {
    use statrs::distribution::{ContinuousCDF, Normal, StudentsT};
    let dof = (support::N_ROWS - 4) as f64;
    let t = 2.0;
    let p_t = 2.0 * StudentsT::new(0.0, 1.0, dof).unwrap().cdf(-t);
    let p_z = 2.0 * Normal::new(0.0, 1.0).unwrap().cdf(-t);
    let point = |p: f64| {
        serde_json::json!([{
            "budget": 0.0, "t_statistic": t, "p_value": p, "is_significant": p < 0.05,
            "group_coefficient": 1.0, "degrees_of_freedom": dof as i64,
            "confidence_level": 0.95
        }])
    };
    let want = serde_json::json!([{"budget": 0.0, "t_statistic": t, "p_value": p_z, "is_significant": true}]);
    assert!(compare_scoped("frontier/self", &want, &point(p_t)).is_ok());
    assert!(
        compare_scoped("frontier/self", &want, &point(p_z)).is_err(),
        "a normal-theory p-value must be refused"
    );
}
